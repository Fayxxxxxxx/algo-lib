  int minRepresentation(string s) {
      int n = s.size();
      s = s + s;          // ①拼成双倍，让环形串可以线性访问

      int i = 0, j = 1;   // ②两个候选起点，先让0和1打

      while (i < n && j < n) {  // ③只要两个候选都合法
          int k = 0;
          while (k < n && s[i+k] == s[j+k]) k++;  // ④找到第一个不同的位置

          if (s[i+k] > s[j+k])   // ⑤i 那边更大
              i = i + k + 1;      //    i 淘汰，跳过 k+1 个
          else                     // ⑥j 那边更大
              j = j + k + 1;      //    j 淘汰，跳过 k+1 个

          if (i == j) j++;        // ⑦不能自己跟自己比，j 往后走一格
      }

      return min(i, j);  // ⑧活下来的那个就是答案
  }

